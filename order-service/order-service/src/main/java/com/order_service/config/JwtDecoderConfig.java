package com.order_service.config;

import org.springframework.beans.factory.annotation.Value;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.security.oauth2.jwt.JwtDecoder;
import org.springframework.security.oauth2.jwt.JwtException;
import org.springframework.security.oauth2.jwt.NimbusJwtDecoder;

import javax.crypto.SecretKey;
import javax.crypto.spec.SecretKeySpec;
import java.nio.charset.StandardCharsets;

@Configuration
public class JwtDecoderConfig {

    @Value("${jwt.secret:1234567890123456789012345678901234567890}")
    private String jwtSecret;

    /**
     * Create a JwtDecoder that validates tokens signed with the symmetric key (HS512)
     * This decoder works with tokens generated by the Auth Service
     */
    @Bean
    public JwtDecoder jwtDecoder() {
        try {
            // Create a SecretKey from the JWT secret
            byte[] secretBytes = jwtSecret.getBytes(StandardCharsets.UTF_8);
            SecretKey secretKey = new SecretKeySpec(secretBytes, 0, secretBytes.length, "HmacSHA512");

            // Create NimbusJwtDecoder with the secret key
            return NimbusJwtDecoder.withSecretKey(secretKey).build();
        } catch (Exception e) {
            throw new JwtException("Failed to create JWT decoder", e);
        }
    }
}





